#!/usr/bin/env node
/** build-sitemap.mjs — regenerate sitemap.xml from tools/cities.mjs. */
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ALL_CITIES } from './cities.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const HOST = process.env.HOST || 'https://djbenthomas.github.io/as-ulike-it/';
const LASTMOD = process.env.LASTMOD || new Date().toISOString().slice(0, 10);

const rows = [
  { loc: HOST, priority: '1.0' },
  ...ALL_CITIES.map((c) => ({ loc: HOST + c.file, priority: c.priority.toFixed(2) })),
  { loc: HOST + 'photo-booth.html', priority: '0.95' },
  // Seasonal / campaign pages. Extensionless to match their canonical URL.
  { loc: HOST + 'christmas-office-parties', priority: '0.95' },
];

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- AS·U·LIKE·IT Entertainment — canonical host: ${HOST}
     NOTE: regenerate with HOST=https://as-ulikeit.com/ after the DNS switch.
     Generated by tools/build-sitemap.mjs — do not hand-edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${rows.map((r) => `  <url>
    <loc>${r.loc}</loc>
    <lastmod>${LASTMOD}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>${r.priority}</priority>
  </url>`).join('\n')}
</urlset>
`;

writeFileSync(join(ROOT, 'sitemap.xml'), xml);
console.log(`sitemap.xml: ${rows.length} urls (host ${HOST})`);
